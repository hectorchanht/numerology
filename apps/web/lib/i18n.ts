/** 轻量外部 store:所有 useLocale() 实例共享同一语言,切换即全局重渲染。 */
let current: Locale = readStored();
const listeners = new Set<() => void>();

export function setLocale(l: Locale): void {
  if (l === current) return;
  current = l;
  try {
    window.localStorage.setItem(LS_KEY, l);
  } catch {
    /* ignore */
  }
  listeners.forEach((fn) => fn());
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/** 当前语言 + 切换 + 翻译函数。默认繁体(zht);选择持久化到 localStorage。 */
export function useLocale(): {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
} {
  const locale = useSyncExternalStore(subscribe, () => current, () => DEFAULT_LOCALE);
  return {
    locale,
    setLocale,
    t: (key, vars) => fmt(STRINGS[locale][key] ?? key, vars),
  };
}

const SWITCH_LABELS: Record<Locale, string> = { zht: "繁", zhs: "简", en: "EN" };

/** `<html lang>` 跟隨界面語言。 */
export const HTML_LANG: Record<Locale, string> = { zht: "zh-Hant", zhs: "zh-Hans", en: "en" };

/** 三向语言切换器:繁 / 简 / EN(分段控件,放在设定页)。 */
export function LocaleSwitch(): React.ReactElement {
  const { locale, setLocale: set } = useLocale();
  return createElement(
    "div",
    {
      className: "seg compact",
      role: "group",
      "aria-label": "language / 語言",
    },
    LOCALES.map((l) =>
      createElement(
        "button",
        {
          key: l,
          type: "button",
          className: locale === l ? "on" : "",
          onClick: () => set(l),
          "aria-pressed": locale === l,
        },
        SWITCH_LABELS[l],
      ),
    ),
  );
}
