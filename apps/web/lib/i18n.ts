export const STRINGS: Record<Locale, Record<TKey, string>> = { zht, zhs, en };

/** 填充模板中的 {name} 占位符。 */
export function fmt(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : `{${k}}`,
  );
}

function readStored(): Locale {
  if (typeof window === "undefined") return DEFAULT_LOCALE;
  try {
    const v = window.localStorage.getItem(LS_KEY);
    if (v === "zht" || v === "zhs" || v === "en") return v;
  } catch {
    /* ignore */
  }
  return DEFAULT_LOCALE;
}

/** 轻量外部 store:所有 useLocale() 实例共享同一语言,切换即全局重渲染。 */
let current: Locale = readStored();
const listeners = new Set<() => void>();

export function setLocale(l: Locale): void {
  if (l === current) return;
  current = l;
  try {
    window.localStorage.setItem(LS_KEY, l);
  } catch {
    /* ignore */
  }
  listeners.forEach((fn) => fn());
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/** 当前语言 + 切换 + 翻译函数。默认繁体(zht);选择持久化到 localStorage。 */
export function useLocale(): {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
} {
  const locale = useSyncExternalStore(subscribe, () => current, () => DEFAULT_LOCALE);
  return {
    locale,
    setLocale,
    t: (key, vars) => fmt(STRINGS[locale][key] ?? key, vars),
  };
}

const SWITCH_LABELS: Record<Locale, string> = { zht: "繁", zhs: "简", en: "EN" };

/** 三向语言切换器:繁 / 简 / EN。放在 masthead。 */
export function LocaleSwitch(): React.ReactElement {
  const { locale, setLocale: set } = useLocale();
  return createElement(
    "div",
    {
      className: "mode-switch",
      style: { marginBottom: 0, marginTop: "0.9rem" },
      role: "group",
      "aria-label": "language / 語言",
    },
    LOCALES.map((l) =>
      createElement(
        "button",
        {
          key: l,
          type: "button",
          className: locale === l ? "active" : "",
          onClick: () => set(l),
          "aria-pressed": locale === l,
        },
        SWITCH_LABELS[l],
      ),
    ),
  );
}
