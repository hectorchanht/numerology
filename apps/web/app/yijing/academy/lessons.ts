/** localStorage 進度鍵 */
export const ACADEMY_PROGRESS_KEY = "yijing-academy-progress";

export interface AcademyProgress {
  [lessonId: string]: { done: boolean; best: number; total: number };
}

export function loadProgress(): AcademyProgress {
  try {
    const raw = localStorage.getItem(ACADEMY_PROGRESS_KEY);
    if (!raw) return {};
    const p = JSON.parse(raw) as AcademyProgress;
    return p && typeof p === "object" ? p : {};
  } catch {
    return {};
  }
}

export function saveProgress(p: AcademyProgress): void {
  try {
    localStorage.setItem(ACADEMY_PROGRESS_KEY, JSON.stringify(p));
  } catch {
    /* 私密模式等寫入失敗時靜默忽略 */
  }
}
