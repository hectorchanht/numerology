/**
 * 构建时把排盘依赖的版本号注入 src/versions.generated.ts。
 * Edge/Workers 运行时没有 node:module(createRequire),无法在运行时读
 * 依赖的 package.json —— 改为构建时写入,运行时只做查表,缺失则 "unknown"。
 * 由 packages/engine 的 build 脚本在 tsc 之前调用。
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);

const DEPS = ["iztro", "lunar-javascript"];

const entries = DEPS.map((name) => {
  let version = "unknown";
  try {
    version = require(`${name}/package.json`).version ?? "unknown";
  } catch {
    /* 未安装或不可读:保持 unknown */
  }
  return `  ${JSON.stringify(name)}: ${JSON.stringify(version)},`;
});

const out = `// AUTO-GENERATED by scripts/gen-versions.mjs — 请勿手改,构建时重新生成。
export const DEPENDENCY_VERSIONS: Record<string, string> = {
${entries.join("\n")}
};
`;

writeFileSync(new URL("../src/versions.generated.ts", import.meta.url), out);
console.log(`[gen-versions] wrote src/versions.generated.ts: ${entries.join(" ")}`);
